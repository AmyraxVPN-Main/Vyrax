function read() {
  try {
    const saved = localStorage.getItem('vyrax-lang');
    if (saved && STRINGS[saved]) return saved;
  } catch {
    /* بی‌اهمیت */
  }
  return mobile && navigator.language.startsWith('fa') ? 'fa' : 'en';
}

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(read);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';
    if (mobile) call('language', { language:lang }).catch(() => {});
    try {
      localStorage.setItem('vyrax-lang', lang);
    } catch {
      /* بی‌اهمیت */
    }
  }, [lang]);

  function t(key, vars) {
    const s = (platform === 'ios' ? IOS_STRINGS[lang]?.[key] : platform === 'macos' ? MAC_STRINGS[lang]?.[key] : undefined) ?? STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '')) : s;
  }

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n بیرون از I18nProvider صدا زده شد.');
  return ctx;
}
