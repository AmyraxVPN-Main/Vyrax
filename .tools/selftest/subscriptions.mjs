import assert from 'node:assert/strict';
import { migrateSubscriptions, scopedProfiles, subscriptionUrl, subscriptionName, subscriptionUsage, subscriptionMetadata, needsSubscriptionName, importLocalSubscription, subscriptionContent } from '../../src/lib/subscriptions.mjs';
import { mergeProfiles, parseImport, profileKey } from '../../src/lib/profiles.mjs';

const url = 'https://subscription.example.test/a?token=demo-only';
const a = { id:'original', name:'Original', protocol:'vless', host:'example.test', port:443, uuid:'00000000-0000-4000-8000-000000000001', sourceId:url, favorite:true, latency:42 };
const migrated = migrateSubscriptions({ profiles:[a], selectedId:a.id });
assert.equal(migrated.subscriptions.length,1);
assert.equal(migrated.subscriptions[0].url,url);
assert.equal(migrated.activeSourceId,migrated.subscriptions[0].id);
assert.equal(migrated.profiles[0].sourceId,migrated.activeSourceId);
assert.deepEqual(migrateSubscriptions(migrated),migrated,'migration is stable');
const refresh = mergeProfiles(migrated.profiles,[{ ...a, id:'new', name:'Renamed' }],migrated.activeSourceId);
assert.equal(refresh[0].id,a.id,'refresh keeps the manual selection ID');
assert.equal(refresh[0].favorite,true);
assert.equal(refresh[0].latency,42);
const both = mergeProfiles(refresh,[{ ...a, id:'different-source' }],'second');
assert.equal(both.length,2,'same endpoint can exist independently in two sources');
assert.equal(scopedProfiles(both,'second')[0].id,'different-source');
assert.equal(scopedProfiles(both,migrated.activeSourceId).length,1);
assert.equal(mergeProfiles(both,[], 'second').length,1,'source removal keeps other servers');
assert.deepEqual(subscriptionUsage('upload=1; download=2; total=100; expire=1700000000;unknown=99;invalid=NaN'),{upload:1,download:2,total:100,expire:1700000000});
assert.equal(subscriptionUsage('total=-1;download=Infinity'),null);
assert.equal(subscriptionName('base64:'+Buffer.from('اشتراک من').toString('base64'),url),'اشتراک من');
assert.equal(subscriptionName('',url),'subscription.example.test');
assert.equal(subscriptionMetadata({ title:'base64:'+Buffer.from('Amyrax-100GB-V2').toString('base64') },url).name,'Amyrax-100GB-V2');
assert.equal(subscriptionMetadata({ title:encodeURIComponent('کاربر اصلی') },url).name,'کاربر اصلی');
assert.equal(subscriptionMetadata({ text:'#profile-title: base64:'+Buffer.from('عنوان فارسی').toString('base64')+'\nvless://example' },url).name,'عنوان فارسی');
assert.equal(subscriptionMetadata({ disposition:"attachment; filename*=UTF-8''%DA%A9%D8%A7%D8%B1%D8%A8%D8%B1%20%D8%A7%D8%B5%D9%84%DB%8C.txt" },url).name,'کاربر اصلی');
assert.equal(subscriptionMetadata({ disposition:'attachment; filename="Amyrax-100GB-V2.yaml"' },url).name,'Amyrax-100GB-V2');
assert.equal(subscriptionMetadata({},url,'Saved name').name,'Saved name');
assert.equal(subscriptionMetadata({},url+'#'+encodeURIComponent('نام لینک')).name,'نام لینک');
assert.equal(subscriptionMetadata({ title:'base64:invalid===' },url).name,'subscription.example.test');
assert.equal(needsSubscriptionName({name:'subscription.example.test',url}),true);
assert.equal(needsSubscriptionName({name:'Actual title',url}),false);
assert.equal(subscriptionMetadata({ title:'base64:U3Vic2NyaXB0aW9u', disposition:'attachment; filename="Amyrax-100GB-V2"' },url,'Subscription').name,'Amyrax-100GB-V2','generic provider title must not hide the real download name');
assert.equal(subscriptionMetadata({ title:'Subscription', disposition:'inline; filename="%DA%A9%D8%A7%D8%B1%D8%A8%D8%B1%20%D8%A7%D8%B5%D9%84%DB%8C"' },url).name,'کاربر اصلی');
assert.equal(subscriptionMetadata({ title:'Subscription', text:'#profile-name: کاربر اصلی' },url).name,'کاربر اصلی');
assert.equal(subscriptionMetadata({ title:'Subscription' },url,'Saved account').name,'Saved account');
assert.equal(subscriptionMetadata({ title:'Subscription' },url+'#Named%20account').name,'Named account');
assert.equal(subscriptionMetadata({ title:'Subscription' },url).name,'Subscription','generic title remains a fallback when nothing else is supplied');
assert.equal(subscriptionMetadata({ title:'Specific title', disposition:'attachment; filename="Subscription.txt"' },url).name,'Specific title');
assert.equal(needsSubscriptionName({name:'Subscription',nameSource:'provider',url}),true,'repair names saved by 0.1.13');
assert.equal(subscriptionUrl(' '+url+' '),url);
for(const invalid of ['file:///C:/test','https://user:password@example.test','javascript:alert(1)'])assert.throws(()=>subscriptionUrl(invalid));
assert.throws(()=>parseImport('invalid subscription',key=>key),'invalid refresh must not yield an empty replacement');
console.log('Subscription migration, scope isolation, refresh identity, headers, URL and invalid-refresh checks passed');

const t = (key, vars) => key === 'sub.imported' ? `Imported subscription ${vars.n}` : key;
const link = 'vless://00000000-0000-4000-8000-000000000001@one.example.test:443?type=ws&path=%2Fvpn&security=tls&sni=one.example.test#Single';
const other = 'trojan://test-only@two.example.test:8443?type=grpc&serviceName=vpn&security=tls#Second';
const single = importLocalSubscription(link, migrated.profiles, migrated.subscriptions, '', t);
assert.equal(single.subscription.kind, 'local');
assert.equal(single.subscription.name, 'Single');
assert.equal(single.subscription.url, undefined);
assert.equal(scopedProfiles(single.catalog, single.subscription.id).length, 1);
assert.deepEqual(scopedProfiles(single.catalog, migrated.activeSourceId), migrated.profiles);
const subs = [...migrated.subscriptions, single.subscription];
const batch = importLocalSubscription([link, other, link].join('\n'), single.catalog, subs, '  سفر\n من  ', t);
assert.equal(batch.subscription.name, 'سفر من');
assert.equal(scopedProfiles(batch.catalog, batch.subscription.id).length, 2, 'dedupe only within this paste');
assert.notEqual(batch.subscription.id, single.subscription.id, 'each import gets its own group');
assert.equal(scopedProfiles(batch.catalog, single.subscription.id).length, 1, 'same endpoint in an earlier group stays intact');
const base64 = importLocalSubscription(Buffer.from([link, other].join('\n')).toString('base64'), [], [], '', t);
assert.equal(base64.profiles.length, 2);
assert.equal(base64.subscription.name, 'Imported subscription 1');
const next = importLocalSubscription([link, other].join('\n'), base64.catalog, [base64.subscription], '', t);
assert.equal(next.subscription.name, 'Imported subscription 2');
const partial = importLocalSubscription(link + '\ninvalid', [], [], '', t);
assert.equal(partial.profiles.length, 1);
assert.equal(partial.errors.length, 1);
const before = JSON.stringify({ profiles:batch.catalog, subscriptions:[...subs, batch.subscription] });
assert.throws(() => importLocalSubscription('invalid', batch.catalog, subs, '', t));
assert.equal(JSON.stringify({ profiles:batch.catalog, subscriptions:[...subs, batch.subscription] }), before, 'failed imports do not mutate the catalog');

const savedLocal = { profiles:batch.catalog, subscriptions:[...subs, batch.subscription], activeSourceId:batch.subscription.id, selectedId:batch.profiles[1].id };
assert.deepEqual(migrateSubscriptions(savedLocal), { profiles:savedLocal.profiles, subscriptions:savedLocal.subscriptions, activeSourceId:savedLocal.activeSourceId }, 'local groups survive reload without a URL');
assert.equal(needsSubscriptionName(single.subscription), false, 'local groups never request remote metadata');
const legacy = { profiles:[{ ...a, sourceId:'' }, { ...a, id:'legacy-second', sourceId:undefined }], selectedId:'legacy-second', activeSourceId:'' };
const legacyCopy = JSON.stringify(legacy);
const repaired = migrateSubscriptions(legacy, 'سرورهای واردشده');
assert.equal(repaired.subscriptions.length, 1, 'legacy anonymous configs form one group');
assert.equal(repaired.subscriptions[0].kind, 'local');
assert.equal(repaired.subscriptions[0].name, 'سرورهای واردشده');
assert.equal(scopedProfiles(repaired.profiles, repaired.activeSourceId).length, 2);
assert.equal(repaired.profiles[1].id, legacy.selectedId);
assert.equal(repaired.profiles[0].favorite, true);
assert.equal(repaired.profiles[0].latency, 42);
assert.equal(JSON.stringify(legacy), legacyCopy, 'migration never mutates the loaded store');
assert.deepEqual(migrateSubscriptions(repaired), repaired, 'legacy grouping is idempotent');
const noSelection = migrateSubscriptions({profiles:legacy.profiles});
assert.equal(noSelection.activeSourceId, noSelection.profiles[0].sourceId, 'missing selection still opens the migrated group');
const staleSource = migrateSubscriptions({profiles:[a], selectedId:a.id, activeSourceId:''});
assert.equal(staleSource.activeSourceId, staleSource.profiles[0].sourceId, 'an empty stale source follows the selected subscription');
const mixed = migrateSubscriptions({ profiles:[a, { ...a, id:'local', sourceId:'' }], selectedId:a.id });
assert.equal(mixed.activeSourceId, mixed.profiles[0].sourceId, 'missing active source follows the selected remote profile');
const orphan = migrateSubscriptions({ profiles:[{ ...a, sourceId:'old-source' }], activeSourceId:'old-source', selectedId:a.id });
assert.equal(orphan.subscriptions[0].id, 'old-source', 'orphaned groups keep their scope');
assert.equal(orphan.activeSourceId, 'old-source');
assert.deepEqual(migrateSubscriptions(orphan), orphan);
assert.deepEqual(migrateSubscriptions({profiles:[],subscriptions:[]}), {profiles:[],subscriptions:[],activeSourceId:''}, 'no empty group is created on startup');
assert.equal(mergeProfiles(batch.catalog, [], batch.subscription.id).length, single.catalog.length, 'deleting one group preserves all other groups');

const content = subscriptionContent(batch.subscription, batch.catalog);
const copied = parseImport(content, t).profiles;
assert.deepEqual(copied.map(profileKey), scopedProfiles(batch.catalog, batch.subscription.id).map(profileKey), 'copy/re-import preserves every connection field');
assert.ok(JSON.parse(content).every(p => !('id' in p) && !('sourceId' in p) && !('favorite' in p) && !('latency' in p)), 'shared data contains no UI state');
assert.equal(subscriptionContent(migrated.subscriptions[0], batch.catalog), url, 'remote subscriptions still share their original URL');
const protocols = ['vless','vmess','trojan','shadowsocks'];
const transports = ['tcp','ws','grpc','httpupgrade','xhttp'];
for (const protocol of protocols) for (const transport of transports) {
  const p = { ...a, protocol, transport, sourceId:'roundtrip', password:'synthetic', method:'aes-256-gcm', cipher:'auto', alterId:0,
    path:'/path', wsHost:'host.example.test', serviceName:'service', tls:true, sni:'tls.example.test', alpn:'h2,http/1.1', insecure:false,
    fingerprint:'chrome', reality:true, publicKey:'test-public-key', shortId:'abcd', flow:'', mode:'auto' };
  const payload = subscriptionContent({ id:'roundtrip', kind:'local' }, [p]);
  assert.equal(profileKey(parseImport(payload, t).profiles[0]), profileKey(p), `${protocol}/${transport} share roundtrip`);
}
assert.throws(() => parseImport('[{"protocol":"vless","host":"example.test","port":443,"uuid":"invalid"}]', t), 'export JSON uses the same validation as other imports');
console.log('Local single/batch imports, independent groups, legacy migration, reload, copy/QR payload and 20 protocol/transport roundtrips passed');
